"""User CSV import (v0.1-compatible Year,Value format; also Entity,Year,Value) and the demo generator."""

from __future__ import annotations

import io
import math
import random

import pandas as pd

from chronos.errors import DataError
from chronos.ingestion.http import read_local
from chronos.ingestion.registry import entry
from chronos.storage.repository import IngestBatch, ObsRow, SeriesMeta, SeriesPayload, SourceInfo

DEMO_INDICATOR = "DEMO_SYNTHETIC_INDEX"
DEMO_ENTITY = "Synthetic World"


def import_csv(path: str, indicator: str, entity: str | None, source_url: str, synthetic: bool = False,
               unit: str | None = None) -> IngestBatch:
    if not source_url.strip():
        raise DataError("--source-url is required: CHRONOS stores, but does not verify, declared provenance")
    fr = read_local(path)
    df = pd.read_csv(io.BytesIO(fr.content))
    cols = {c.lower(): c for c in df.columns}
    if not {"year", "value"} <= set(cols):
        raise DataError("Required CSV columns: Year,Value (optionally Entity)")
    if "entity" in cols:
        groups = list(df.groupby(cols["entity"]))
    elif entity:
        groups = [(entity, df)]
    else:
        raise DataError("Pass --entity or include an Entity column")
    kind = "synthetic" if synthetic else "real"
    src = entry("synthetic").info() if synthetic else entry("user-csv").info()
    payloads = []
    for ent, g in groups:
        years = pd.to_numeric(g[cols["year"]], errors="coerce")
        values = pd.to_numeric(g[cols["value"]], errors="coerce")
        ok = years.notna() & values.notna()
        rows = [ObsRow(int(y), float(v)) for y, v in zip(years[ok], values[ok], strict=True)]
        payloads.append(SeriesPayload(SeriesMeta(indicator, str(ent), src.source_id, source_url, "Value",
                                                 unit=unit, data_kind=kind,
                                                 description=f"User-declared source: {source_url}"), rows))
    return IngestBatch(src, source_url, fr.url, fr.sha256, payloads, notes="user-declared provenance (unverified)")


def demo_batch() -> IngestBatch:
    """Byte-for-byte the v0.1 synthetic generator (seed 104), labelled SYNTHETIC."""
    rng = random.Random(104)
    val = 30.0
    rows = []
    for year in range(1900, 2026):
        growth = 0.013 if year < 1950 else 0.024 if year < 1980 else 0.007 if year < 2000 else 0.003
        val *= math.exp(growth + rng.gauss(0, 0.007))
        rows.append(ObsRow(year, val, "observed"))
    src: SourceInfo = entry("synthetic").info()
    meta = SeriesMeta(DEMO_INDICATOR, DEMO_ENTITY, "synthetic", "chronos-demo", "generated", unit="index",
                      description="SYNTHETIC: generated by chronos demo; not historical data", data_kind="synthetic")
    return IngestBatch(src, "chronos-demo", "SYNTHETIC:generated-by-chronos-demo", None, [SeriesPayload(meta, rows)],
                       source_version="v0.1-generator-seed-104")
